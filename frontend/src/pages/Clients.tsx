import { useCallback, useEffect, useState, type FormEvent } from "react";
import * as api from "../api";
import { useAuth } from "../auth";
import { EmptyState, ErrorNotice, Loading } from "../components/ui";
import { formatDate } from "../format";
import type {
  AgencyDashboard,
  Client,
  DashboardClient,
  SeverityTotals,
} from "../types";
import { canManageClients } from "../types";
import { buildHash } from "../router";

function message(err: unknown): string {
  return err instanceof Error ? err.message : "Something went wrong.";
}

function openTotal(c: SeverityTotals): number {
  return c.critical + c.high + c.medium + c.low + c.info;
}

function Counts({ counts }: { counts: SeverityTotals }) {
  const parts = (
    [
      ["critical", "Critical"],
      ["high", "High"],
      ["medium", "Medium"],
      ["low", "Low"],
    ] as const
  ).filter(([k]) => counts[k] > 0);
  if (parts.length === 0 && counts.info === 0) return <span>None</span>;
  return (
    <span>
      {parts.map(([k, label]) => `${counts[k]} ${label}`).join(", ") ||
        `${counts.info} informational`}
    </span>
  );
}

function ClientForm({
  initial,
  onSave,
  onCancel,
  submitLabel,
}: {
  initial?: Client;
  onSave: (input: api.ClientInput) => Promise<void>;
  onCancel?: () => void;
  submitLabel: string;
}) {
  const [name, setName] = useState(initial?.name ?? "");
  const [email, setEmail] = useState(initial?.contact_email ?? "");
  const [notes, setNotes] = useState(initial?.notes ?? "");
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);

  const submit = async (event: FormEvent) => {
    event.preventDefault();
    setBusy(true);
    setError(null);
    try {
      await onSave({
        name: name.trim(),
        contact_email: email.trim() || null,
        notes: notes.trim() || null,
      });
      if (!initial) {
        setName("");
        setEmail("");
        setNotes("");
      }
    } catch (err) {
      setError(message(err));
    } finally {
      setBusy(false);
    }
  };

  const id = initial?.id ?? "new";
  return (
    <form className="form-stack" onSubmit={(e) => void submit(e)}>
      {error && <ErrorNotice message={error} />}
      <label className="toolbar-field">
        <span className="field-label">Client name</span>
        <input
          className="input"
          value={name}
          maxLength={120}
          required
          onChange={(e) => setName(e.target.value)}
        />
      </label>
      <label className="toolbar-field">
        <span className="field-label">Contact email (optional)</span>
        <input
          className="input"
          type="email"
          value={email}
          maxLength={254}
          onChange={(e) => setEmail(e.target.value)}
        />
      </label>
      <label className="toolbar-field">
        <span className="field-label">Private notes (optional)</span>
        <textarea
          className="input"
          rows={3}
          value={notes}
          maxLength={2000}
          aria-describedby={`notes-hint-${id}`}
          onChange={(e) => setNotes(e.target.value)}
        />
        <span id={`notes-hint-${id}`} className="muted small">
          Only your team sees these. They are never put in a report or a shared
          link.
        </span>
      </label>
      <div className="row">
        <button className="btn" type="submit" disabled={busy}>
          {busy ? "Saving…" : submitLabel}
        </button>
        {onCancel && (
          <button type="button" className="btn-ghost" onClick={onCancel}>
            Cancel
          </button>
        )}
      </div>
    </form>
  );
}

function BrandingCard({ manage }: { manage: boolean }) {
  const [name, setName] = useState("");
  const [saved, setSaved] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);
  useEffect(() => {
    api
      .getBranding()
      .then((b) => setName(b.agency_name ?? ""))
      .catch((err: unknown) => setError(message(err)));
  }, []);
  const submit = async (event: FormEvent) => {
    event.preventDefault();
    setError(null);
    setSaved(null);
    try {
      const result = await api.setBranding(name.trim() || null);
      setName(result.agency_name ?? "");
      setSaved("Saved.");
    } catch (err) {
      setError(message(err));
    }
  };
  return (
    <section className="card" aria-labelledby="branding-h">
      <h2 id="branding-h">Report branding</h2>
      <p className="muted small">
        Your agency name is printed as “Prepared by” on the PDF reports you
        create from now on, and on shared report pages. Reports made earlier are
        not changed. “Generated by SecureScope” always stays on the report.
      </p>
      {error && <ErrorNotice message={error} />}
      <form className="row" onSubmit={(e) => void submit(e)}>
        <label className="toolbar-field">
          <span className="field-label">Agency name</span>
          <input
            className="input"
            value={name}
            maxLength={80}
            disabled={!manage}
            onChange={(e) => setName(e.target.value)}
          />
        </label>
        {manage && (
          <button className="btn" type="submit">
            Save name
          </button>
        )}
        {saved && (
          <span role="status" className="muted small">
            {saved}
          </span>
        )}
      </form>
    </section>
  );
}

function ClientBlock({
  row,
  clients,
  manage,
  onAssign,
}: {
  row: DashboardClient;
  clients: Client[];
  manage: boolean;
  onAssign: (targetId: string, clientId: string | null) => void;
}) {
  return (
    <section className="card" aria-labelledby={`c-${row.client_id ?? "none"}`}>
      <h3 id={`c-${row.client_id ?? "none"}`}>{row.name}</h3>
      <p className="muted small">
        {row.sites.length} {row.sites.length === 1 ? "website" : "websites"}
        {" · "}Open findings: <Counts counts={row.open_findings} />
        {row.worst_grade ? ` · Lowest grade ${row.worst_grade}` : ""}
        {row.last_scan_at ? ` · Last scan ${formatDate(row.last_scan_at)}` : ""}
      </p>
      {row.sites.length === 0 ? (
        <p className="muted">No websites assigned yet.</p>
      ) : (
        <div
          className="table-wrap"
          role="region"
          tabIndex={0}
          aria-label={`Websites of ${row.name} (scrolls sideways on small screens)`}
        >
          <table>
            <thead>
              <tr>
                <th scope="col">Website</th>
                <th scope="col">Latest score</th>
                <th scope="col">Open findings</th>
                <th scope="col">Last scan</th>
                {manage && <th scope="col">Client</th>}
              </tr>
            </thead>
            <tbody>
              {row.sites.map((s) => (
                <tr key={s.target_id}>
                  <th scope="row">
                    {s.last_scan_id ? (
                      <a href={buildHash("findings", s.last_scan_id)}>
                        {s.hostname}
                      </a>
                    ) : (
                      s.hostname
                    )}
                    {!s.verified && (
                      <span className="muted small"> (not verified)</span>
                    )}
                  </th>
                  <td>
                    {s.score === null
                      ? "Not scanned"
                      : `${s.score} (${s.grade})`}
                  </td>
                  <td>
                    {s.last_scan_id ? (
                      <>
                        {openTotal(s.open_findings)}{" "}
                        <span className="muted small">
                          (<Counts counts={s.open_findings} />)
                        </span>
                      </>
                    ) : (
                      "–"
                    )}
                  </td>
                  <td>{formatDate(s.last_scan_at)}</td>
                  {manage && (
                    <td>
                      <select
                        className="input"
                        aria-label={`Client for ${s.hostname}`}
                        value={row.client_id ?? ""}
                        onChange={(e) =>
                          onAssign(s.target_id, e.target.value || null)
                        }
                      >
                        <option value="">Not assigned</option>
                        {clients.map((c) => (
                          <option key={c.id} value={c.id}>
                            {c.name}
                          </option>
                        ))}
                      </select>
                    </td>
                  )}
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}
    </section>
  );
}

export default function Clients() {
  const { organization } = useAuth();
  const manage = organization ? canManageClients(organization.role) : false;
  const [dashboard, setDashboard] = useState<AgencyDashboard | null>(null);
  const [clients, setClients] = useState<Client[]>([]);
  const [error, setError] = useState<string | null>(null);
  const [editing, setEditing] = useState<string | null>(null);
  const [confirmDelete, setConfirmDelete] = useState<string | null>(null);

  const load = useCallback(async () => {
    try {
      const [d, c] = await Promise.all([api.getDashboard(), api.listClients()]);
      setDashboard(d);
      setClients(c);
      setError(null);
    } catch (err) {
      setError(message(err));
    }
  }, []);
  useEffect(() => {
    let live = true;
    Promise.all([api.getDashboard(), api.listClients()])
      .then(([d, c]) => {
        if (!live) return;
        setDashboard(d);
        setClients(c);
      })
      .catch((err: unknown) => live && setError(message(err)));
    return () => {
      live = false;
    };
  }, []);

  const assign = async (targetId: string, clientId: string | null) => {
    try {
      await api.assignClient(targetId, clientId);
      await load();
    } catch (err) {
      setError(message(err));
    }
  };

  return (
    <div className="page">
      <h1>Clients</h1>
      <p className="muted">
        Group your websites by client and see where each one stands, from the
        scans you have run. Nothing here is estimated: a site that has never
        been scanned says so.
      </p>
      {error && <ErrorNotice message={error} />}
      {!dashboard && !error && <Loading label="Loading clients…" />}

      {dashboard && dashboard.total_clients === 0 && (
        <EmptyState title="No clients yet">
          {manage
            ? "Add your first client below, then put its websites under it."
            : "An owner or admin can add clients."}
        </EmptyState>
      )}
      {dashboard?.clients.map((row) => (
        <ClientBlock
          key={row.client_id ?? "none"}
          row={row}
          clients={clients}
          manage={manage}
          onAssign={(t, c) => void assign(t, c)}
        />
      ))}

      {clients.length > 0 && (
        <section className="card" aria-labelledby="client-list-h">
          <h2 id="client-list-h">Client details</h2>
          <ul className="plain-list">
            {clients.map((c) => (
              <li key={c.id}>
                {editing === c.id ? (
                  <ClientForm
                    initial={c}
                    submitLabel="Save changes"
                    onCancel={() => setEditing(null)}
                    onSave={async (input) => {
                      await api.updateClient(c.id, input);
                      setEditing(null);
                      await load();
                    }}
                  />
                ) : (
                  <>
                    <h3>{c.name}</h3>
                    <p className="muted small">
                      {c.contact_email ?? "No contact email"} · {c.site_count}{" "}
                      {c.site_count === 1 ? "website" : "websites"}
                    </p>
                    {c.notes && (
                      <p className="small" style={{ whiteSpace: "pre-wrap" }}>
                        {c.notes}
                      </p>
                    )}
                    {manage && (
                      <div className="row">
                        <button
                          type="button"
                          className="btn-ghost"
                          onClick={() => setEditing(c.id)}
                          aria-label={`Edit ${c.name}`}
                        >
                          Edit
                        </button>
                        {confirmDelete === c.id ? (
                          <>
                            <span className="small">
                              Remove this client? Its websites stay in your
                              workspace.
                            </span>
                            <button
                              type="button"
                              className="btn-danger"
                              onClick={() =>
                                void api
                                  .deleteClient(c.id)
                                  .then(() => {
                                    setConfirmDelete(null);
                                    return load();
                                  })
                                  .catch((err: unknown) =>
                                    setError(message(err)),
                                  )
                              }
                            >
                              Yes, remove
                            </button>
                            <button
                              type="button"
                              className="btn-ghost"
                              onClick={() => setConfirmDelete(null)}
                            >
                              Keep
                            </button>
                          </>
                        ) : (
                          <button
                            type="button"
                            className="btn-ghost"
                            onClick={() => setConfirmDelete(c.id)}
                            aria-label={`Remove ${c.name}`}
                          >
                            Remove
                          </button>
                        )}
                      </div>
                    )}
                  </>
                )}
              </li>
            ))}
          </ul>
        </section>
      )}

      {manage && (
        <section className="card" aria-labelledby="add-client-h">
          <h2 id="add-client-h">Add a client</h2>
          <ClientForm
            submitLabel="Add client"
            onSave={async (input) => {
              await api.createClient(input);
              await load();
            }}
          />
        </section>
      )}

      <BrandingCard manage={manage} />
    </div>
  );
}
