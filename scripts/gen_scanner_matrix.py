"""Regenerate docs/scanner-test-matrix.md from the rule guidance and a recorded test run.

Usage: record which rules the tests produce (a pytest plugin that wraps Finding.__init__ and dumps
{rule_id: count} as JSON), then: python3 scripts/gen_scanner_matrix.py rules_seen.json > docs/scanner-test-matrix.md
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCANNER = ROOT / "backend" / "app" / "scanner"
THIN = 3


def emitters() -> dict[str, tuple[str, str]]:
    found: dict[str, tuple[str, str]] = {}
    pattern = re.compile(r'id="(SS-[A-Z0-9-]+)"[^)]*?severity=Severity\.(\w+)', re.DOTALL)
    for path in sorted(SCANNER.glob("*.py")):
        for rule, sev in pattern.findall(path.read_text()):
            found.setdefault(rule, (path.name, sev))
    return found


def main() -> None:
    seen: dict[str, int] = json.loads(Path(sys.argv[1]).read_text())
    guidance = json.loads((ROOT / "frontend" / "src" / "guidance.json").read_text())
    where = emitters()
    rows = []
    for rule in sorted(guidance):
        file, sev = where.get(rule, ("(built dynamically)", "varies"))
        count = seen.get(rule, 0)
        flag = "NOT COVERED" if count == 0 else ("thin" if count < THIN else "ok")
        rows.append(
            (rule, sev, file, guidance[rule].get("detection", "?"), count, flag)
        )
    print("# Scanner test matrix\n")
    print(
        "Generated by `scripts/gen_scanner_matrix.py` from the rule guidance and a recorded full test run."
    )
    print(
        f"A rule is **thin** when the whole suite produces it fewer than {THIN} times.\n"
    )
    print(
        "| Rule | Severity | Emitted in | Detection | Times produced by tests | Coverage |"
    )
    print("|---|---|---|---|---|---|")
    for r in rows:
        print("| " + " | ".join(str(x) for x in r) + " |")
    print(
        f"\n{len(rows)} rules; {sum(1 for r in rows if r[5] == 'NOT COVERED')} not covered, "
        f"{sum(1 for r in rows if r[5] == 'thin')} thin."
    )


main()
